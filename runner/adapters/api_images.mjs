/**
 * Image tools: generate_image and edit_image call the OpenAI Images API (`/images/generations`, `/images/edits`) with
 * this computer's image service (image_service.mjs), in a room whose owner turned drawing on. An API member calls them
 * as tools and its images go out with its submit_chat answer; a CLI member runs `codiscuss launch image`, which calls
 * `run_image_tool` too. The images are saved as the member's room attachments (and, on request, as new project files). The model never sees the image bytes; inputs come from room attachments or project files by
 * reference. The Images API rather than the Responses `image_generation` tool, because only the Images API serves every
 * GPT Image model and the SVG, GIF, markup and complexity options (measured against the OpenAI docs, 2026-11-10).
 */
import { createHash, randomUUID } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { in_draft_space } from '../account_space.mjs';
import { site_fetch as entry_fetch } from '../entry_client.mjs';
import { read_project_bytes, write_new_project_file } from './api_files.mjs';

// Complex prompts, GIF frames and the higher qualities can take minutes.
const IMAGE_TIMEOUT_MS = 600_000;
const SITE_TIMEOUT_MS = 30_000;
// While the image request runs, its activity is refreshed at the runner's renewal pace, so the room does not take a long
// generation (up to IMAGE_TIMEOUT_MS) for a stalled execution; the request's own timeout still ends a hung call.
const HEARTBEAT_MS = 30_000;
// The JSON edit endpoint takes an image as a data URL of at most this many characters.
const MAX_DATA_URL_CHARS = 20_971_520;
const MAX_INPUT_BYTES = 50 * 1024 * 1024;
const MAX_INPUT_IMAGES = 16;
export const MAX_MESSAGE_ATTACHMENTS = 10;
// Where a writing member's images are also kept inside its project (or its room's folder of the draft space).
const IMAGE_FOLDER = 'images';
const ERROR_EXCERPT_CHARS = 600;
const ATTACHMENT_ID = /^[a-f0-9]{32}$/;
const EXTENSIONS = { png: 'png', jpeg: 'jpg', webp: 'webp', gif: 'gif', svg: 'svg' };
const IMAGE_TYPES = [[[0x89, 0x50, 0x4e, 0x47], 'image/png'], [[0xff, 0xd8, 0xff], 'image/jpeg'], [[0x47, 0x49, 0x46, 0x38], 'image/gif']];
export const IMAGE_TOOLS = ['generate_image', 'edit_image'];
// Images generated by executions that ended without an answer, kept so a later execution can send them instead of
// paying to draw them again; the oldest are dropped past this many.
const MAX_UNSENT = 20;

const TEXT = { type: 'string' };
const integer = (minimum, maximum, description) => ({ type: 'integer', minimum, maximum, description });
const choice = (values, description) => ({ type: 'string', enum: values, description });
const SOURCE = { type: 'object', additionalProperties: false, description: '二选一：房间附件 ID，或项目内图片路径',
  properties: { attachment_id: { ...TEXT, description: '消息附件的 ID（32 位十六进制）' }, file_path: { ...TEXT, description: '项目目录内的图片路径' } } };

/** Output options shared by both tools; formats differ, as SVG cannot come from an edit. */
function output_options(formats) {
  return {
    prompt: { ...TEXT, maxLength: 32000, description: '要画什么、怎么改；风格、构图、文字内容都写在这里' },
    size: { ...TEXT, description: 'auto（默认）、1024x1024、1536x1024、1024x1536，或 GPT Image 2 及以后的任意 宽x高：两边都是 16 的倍数，长宽比 1:3 到 3:1，最长边 3840，总像素 655360 到 8294400，超过 2560x1440 为实验性' },
    quality: choice(['auto', 'low', 'medium', 'high', 'xhigh', 'max'], '渲染质量，默认 auto；xhigh、max 只有 2.5、2.6 系列支持；草稿用 low'),
    complexity: choice(['low', 'medium', 'high'], '规划强度（2.6 系列），与质量无关；文字多、版式密集时用 high（默认），越高越慢、越可能改动多余内容'),
    background: choice(['auto', 'opaque', 'transparent'], '背景，默认 auto；transparent 须配 png 或 webp'),
    output_format: choice(formats, `文件格式，默认 png；jpeg 最快；gif 为动图（2.6 系列，不能带蒙版）${formats.includes('svg') ? '；svg 为矢量图（2.6 系列，只能 n=1）' : ''}`),
    output_compression: integer(0, 100, '仅 jpeg、webp：压缩率，默认 100'),
    n: integer(1, MAX_MESSAGE_ATTACHMENTS, '张数，默认 1'),
    moderation: choice(['auto', 'low'], '内容审核强度，默认 auto；low 较宽松'),
    frame_count: integer(2, 16, '仅 gif：帧数，默认 9'),
    frame_duration_ms: integer(20, 2000, '仅 gif：每帧毫秒数，默认 200，按 10 毫秒取整'),
    ...(formats.includes('svg') ? {
      svg_reasoning_effort: choice(['none', 'minimal', 'low', 'medium', 'high', 'xhigh', 'max'], '仅 svg：撰写矢量图的推理强度'),
      svg_model: { ...TEXT, description: '仅 svg：撰写矢量图的模型，只有账号开通了选择时才填' },
    } : {}),
    file_name: { ...TEXT, maxLength: 80, description: '附件文件名（不含扩展名），多张时自动加序号' },
    save_path: { ...TEXT, description: '可写项目时另存为项目文件（相对项目目录，扩展名按格式自动补；多张时自动加序号；不覆盖已有文件）' },
  };
}

/** Describe one tool with an explicit input schema. */
function tool(name, description, properties, required) {
  return { name, description, parameters: { type: 'object', properties, required, additionalProperties: false } };
}

/** The image tools this member gets: none unless its profile names an image model. */
export function image_tools(image) {
  if (!image) return [];
  const cost = `每次调用都调用图片模型 ${image.model} 并计费，想清楚要求再调用，不要为试探反复生成`;
  return [
    tool('generate_image', `按文字生成图片（含 GIF 动图、SVG 矢量图）；${cost}。图片存为本次执行的附件，随 submit_chat 发出；你看不到图片内容`,
      output_options(['png', 'jpeg', 'webp', 'gif', 'svg']), ['prompt']),
    tool('edit_image', `按文字修改或合成已有图片：images 给 1 到 ${MAX_INPUT_IMAGES} 张参考图（第一张为主图）；mask 是带透明通道、与主图同尺寸的 PNG，透明处为要重画的区域（仅作提示，模型不一定严格按形状）；markup 是叠在主图上的透明 PNG 标注层（圈出、画箭头、写批注，2.5、2.6 系列），不能与 mask 同用；${cost}`,
      { images: { type: 'array', minItems: 1, maxItems: MAX_INPUT_IMAGES, items: SOURCE }, mask: SOURCE, markup: SOURCE,
        input_fidelity: choice(['low', 'high'], '保留输入图风格与面部特征的力度，只有 gpt-image-1.5 接受 high；GPT Image 2 及以后不要填'),
        ...output_options(['png', 'jpeg', 'webp', 'gif']) }, ['images', 'prompt']),
  ];
}

/** Whether a tool name is one of the image tools. */
export function is_image_tool(name) {
  return IMAGE_TOOLS.includes(name);
}

/** The MIME type of image bytes, or '' when they are not a raster image the Images API reads. */
function image_type(data) {
  for (const [signature, type] of IMAGE_TYPES) if (signature.every((byte, index) => data[index] === byte)) return type;
  if (data.subarray(0, 4).toString('latin1') === 'RIFF' && data.subarray(8, 12).toString('latin1') === 'WEBP') return 'image/webp';
  return '';
}

/** Fetch one room path with this execution's member credential. */
async function site_fetch(context, path, init = {}) {
  context.signal.throwIfAborted();
  return entry_fetch(`${context.site}/api/rooms/${context.room}${path}`, { redirect: 'error', ...init,
    headers: { 'X-Discussion-Token': context.token, ...init.headers },
    signal: AbortSignal.any([context.signal, AbortSignal.timeout(SITE_TIMEOUT_MS)]) });
}

/** Read one input image from a room attachment or a project file, as a data URL for the JSON edit request. */
async function source_url(context, source, label) {
  if (!source || typeof source !== 'object') throw new Error(`${label} 须为 {attachment_id} 或 {file_path}`);
  const { attachment_id, file_path } = source;
  if (Boolean(attachment_id) === Boolean(file_path)) throw new Error(`${label} 须且只能填 attachment_id 或 file_path 之一`);
  let data;
  if (attachment_id) {
    if (!ATTACHMENT_ID.test(attachment_id)) throw new Error(`${label} 的 attachment_id 须为 32 位十六进制`);
    const response = await site_fetch(context, `/attachments/${attachment_id}/content`);
    if (!response.ok) throw new Error(`${label} 的附件 ${attachment_id} 读取失败（HTTP ${response.status}）`);
    data = Buffer.from(await response.arrayBuffer());
  } else {
    if (!context.project) throw new Error(`${label}：本房间没有项目目录，只能用 attachment_id`);
    data = read_project_bytes(context.project, file_path, MAX_INPUT_BYTES).data;
  }
  const type = image_type(data);
  if (!type) throw new Error(`${label} 不是 PNG、JPEG、WebP 或 GIF 图片`);
  const url = `data:${type};base64,${data.toString('base64')}`;
  if (url.length > MAX_DATA_URL_CHARS) throw new Error(`${label} 太大（${data.length} 字节），请换一张约 15 MB 以内的图片`);
  return { image_url: url };
}

/** The request body: model and documented options only, unset ones left to the API's defaults. */
async function image_body(context, name, args) {
  if (typeof args.prompt !== 'string' || !args.prompt.trim()) throw new Error('prompt 不能为空');
  const body = { model: context.image.model, prompt: args.prompt };
  for (const key of ['size', 'quality', 'complexity', 'background', 'output_format', 'output_compression', 'n', 'moderation',
    'frame_count', 'frame_duration_ms', 'input_fidelity']) if (args[key] !== undefined && args[key] !== null) body[key] = args[key];
  if (args.svg_reasoning_effort || args.svg_model) body.svg = { ...(args.svg_model ? { model: args.svg_model } : {}),
    ...(args.svg_reasoning_effort ? { reasoning: { effort: args.svg_reasoning_effort } } : {}) };
  if (name === 'edit_image') {
    if (!Array.isArray(args.images) || !args.images.length || args.images.length > MAX_INPUT_IMAGES) throw new Error(`images 须为 1 到 ${MAX_INPUT_IMAGES} 张图片`);
    if (args.mask && args.markup) throw new Error('mask 与 markup 不能同时使用');
    body.images = [];
    for (const [index, source] of args.images.entries()) body.images.push(await source_url(context, source, `images[${index}]`));
    if (args.mask) body.mask = await source_url(context, args.mask, 'mask');
    if (args.markup) body.markup = await source_url(context, args.markup, 'markup');
  }
  return body;
}

/** Call the Images API; a refusal comes back with the provider's own reason so the model can correct the call. */
async function images_request(context, name, path, body) {
  let response, data = null;
  const heartbeat = setInterval(() => context.on_activity?.('tool', name), HEARTBEAT_MS);
  try {
    try {
      response = await fetch(`${context.image.base_url}${path}`, { method: 'POST', redirect: 'error',
        headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${context.image.key}` }, body: JSON.stringify(body),
        signal: AbortSignal.any([context.signal, AbortSignal.timeout(IMAGE_TIMEOUT_MS)]) });
    } catch (error) {
      context.signal.throwIfAborted();
      // The request may have been served and billed; the model decides whether to try again.
      throw new Error(`图片接口请求超时或连接失败（结果不明，可能已计费）：${error.message}`);
    }
    try { data = await response.json(); } catch { /* Not JSON. */ }
  } finally { clearInterval(heartbeat); }
  if (!response.ok) {
    const reason = data?.error ? [data.error.code, data.error.message].filter(Boolean).join('：') : '';
    throw new Error(`图片接口返回 HTTP ${response.status}${reason ? `：${reason.slice(0, ERROR_EXCERPT_CHARS)}` : ''}`);
  }
  if (!Array.isArray(data?.data) || !data.data.length || data.data.some(item => typeof item.b64_json !== 'string')) throw new Error('图片接口没有返回图片');
  return data;
}

/** A file name the site accepts: no path or control characters, numbered when one call returns several. */
function file_name(args, index, count, extension) {
  const base = String(args.file_name || '').replace(/[/\\\x00-\x1f\x7f]/g, '').trim().slice(0, 80) || `image-${new Date().toISOString().slice(0, 19).replace(/[-:T]/g, '')}`;
  return `${base}${count > 1 ? `-${index + 1}` : ''}.${extension}`;
}

/** The project path for one image: the requested one, its extension set by the format, numbered when several. */
function numbered_path(path, index, count, extension) {
  const stem = path.replace(/\.[A-Za-z0-9]{1,5}$/, '');
  return `${stem}${count > 1 ? `-${index + 1}` : ''}.${extension}`;
}

/** The private file listing a member's generated images that no answer has sent yet, in the room's runner directory. */
function unsent_file(context) {
  return join(context.directory, `api-images-${createHash('sha256').update(context.participant).digest('hex').slice(0, 16)}.json`);
}

/** Images this member generated in earlier executions that ended without sending them: `[{attachment_id, file_name, created_at}]`. */
export function unsent_images(context) {
  try { return JSON.parse(readFileSync(unsent_file(context), 'utf8')).filter(item => ATTACHMENT_ID.test(item?.attachment_id || '')); }
  catch { return []; }
}

/** Replace the unsent list; written at once, so an execution that fails or crashes later still leaves it. */
function save_unsent(context, items) {
  writeFileSync(unsent_file(context), JSON.stringify(items.slice(-MAX_UNSENT)), { mode: 0o600 });
}

/** Drop images an answer has just sent from the unsent list. */
export function forget_sent_images(context, ids) {
  if (!ids?.length) return;
  const left = unsent_images(context).filter(item => !ids.includes(item.attachment_id));
  save_unsent(context, left);
}

/** Upload one image as an attachment of this execution; the answer links it. */
async function upload(context, name, data) {
  const query = new URLSearchParams({ actor: context.participant, file_name: name, submission_id: randomUUID() });
  const response = await site_fetch(context, `/attachments?${query}`, { method: 'POST', body: data,
    headers: { 'Content-Type': 'application/octet-stream', 'Content-Length': String(data.length) } });
  const result = await response.json().catch(() => ({}));
  if (!response.ok) throw new Error(`图片已生成，但存为附件失败（HTTP ${response.status}${result.error ? `：${result.error}` : ''}）`);
  return result.attachment;
}

/**
 * Run one image tool. A refused or failed call returns its reason to the model; a stop still ends the execution.
 * @returns {{images?: object[], error?: string}} the model-facing result.
 */
export async function run_image_tool(context, name, args) {
  // Images already saved stay listed when a later one fails, since they are attached to the answer regardless.
  const images = [];
  try {
    if (args.save_path !== undefined && !context.project?.writable) throw new Error('save_path 需要可写的项目目录');
    // Without a requested path, a copy is kept under images/ so the room's files hold what was drawn: by a member that
    // may write its project, and in a room's own folder of the draft space whatever the member's access.
    const main = context.project?.roots[0];
    const keeper = main?.writable ? context.project
      : main && context.home && in_draft_space(context.home, main.root) ? { ...context.project, writable: true, roots: [{ ...main, writable: true }] } : null;
    const body = await image_body(context, name, args);
    const data = await images_request(context, name, name === 'edit_image' ? '/images/edits' : '/images/generations', body);
    const format = data.output_format || body.output_format || 'png';
    const extension = EXTENSIONS[format] || format;
    for (const [index, item] of data.data.entries()) {
      const bytes = Buffer.from(item.b64_json, 'base64');
      const image = { size: bytes.length };
      const name = file_name(args, index, data.data.length, extension);
      const kept = args.save_path ? numbered_path(args.save_path, index, data.data.length, extension) : keeper ? `${IMAGE_FOLDER}/${randomUUID().slice(0, 6)}-${name}` : '';
      if (kept) {
        const saved = write_new_project_file(args.save_path ? context.project : keeper, kept, bytes);
        context.on_edits?.([saved.path]);
        image.saved_path = saved.shown;
      }
      const attachment = await upload(context, name, bytes);
      context.generated_attachments.push(attachment.id);
      save_unsent(context, [...unsent_images(context), { attachment_id: attachment.id, file_name: attachment.file_name, created_at: new Date().toISOString() }]);
      images.push({ ...image, attachment_id: attachment.id, file_name: attachment.file_name, ...(item.revised_prompt ? { revised_prompt: item.revised_prompt } : {}) });
    }
    return { images, output_format: format, ...Object.fromEntries(['size', 'quality', 'background', 'usage', 'svg_usage']
      .filter(key => data[key] !== undefined).map(key => [key, data[key]])),
    note: '图片已存为本次执行的附件，submit_chat 时自动随回答发出；你看不到图片内容，回答里不要描述没看到的细节' };
  } catch (error) {
    if (context.signal.aborted) throw error;
    return { error: String(error.message || error).replaceAll(context.image.key, '[已隐藏]'), ...(images.length ? { images } : {}) };
  }
}
